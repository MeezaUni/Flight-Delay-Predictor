    try:
        for col in categorical_columns:
            input_data[col] = encoders[col].transform(input_data[col])
    except ValueError as e:
        return f"Error: Unrecognized input for Airline or Airport. Ensure it matches the dataset."

    # 3. Make the prediction
    prediction = rf_model.predict(input_data)

    # 4. Format the output
    if prediction[0] == 1:
        return "Predicted Status: Delayed"
    else:
        return "Predicted Status: On Time"

